"""
SQL sub-agent: natural-language question -> SQL -> checked -> executed -> rows.

    question --> LLM writes SQL (structured output: {sql, reason})
             --> no SQL?           status "no_query"  (write request / not answerable)
             --> layer 1 check     unsafe  -> status "rejected", never executed
             --> layer 2 execute   (read-only connection, authorizer, timeout, row cap)
             --> parse/run error?  show the model its SQL + the error, retry once
             --> rows              status "ok"

The SQL is always generated by the LLM from the schema; nothing is
hard-coded per question. The agent returns data, not prose: the coordinator
(or the API caller) decides how to phrase the answer, and the generated SQL is
always part of the result so it can be inspected.
"""

import logging
import time
from dataclasses import asdict, dataclass, field
from datetime import date
from pathlib import Path

from langchain_core.language_models import BaseChatModel
from langchain_core.messages import HumanMessage, SystemMessage
from pydantic import BaseModel, Field

from app.db.executor import SQLExecutionError, SQLPermissionError, list_tables, run_read_only
from app.db.schema_context import describe_database
from app.db.sql_safety import InvalidSQLError, UnsafeSQLError, validate_select

logger = logging.getLogger(__name__)

SYSTEM_PROMPT = """You translate questions about the sales data of Helix Pharma Distribution into ONE SQLite query.
Today's date is {today}.

Rules:
- Write a single SELECT statement (WITH ... SELECT is fine).
- If the user asks to add, change or delete data, do not write a query: set sql to null and say the database is read-only.
- If the question cannot be answered from these tables, set sql to null and say what is missing.
- Use only the tables and columns below and join through the foreign keys.
- Sales / revenue = SUM(order_items.quantity * order_items.unit_price) over orders with status = 'delivered', unless the question says otherwise.
- Dates are TEXT 'YYYY-MM-DD': filter with BETWEEN or strftime('%Y-%m', order_date). Q1 = Jan-Mar, Q2 = Apr-Jun, Q3 = Jul-Sep 2026.
- Questions may be in Persian; the data is in English. Use the exact values listed under "Values found in the data" (e.g. تهران -> 'Tehran').
- Give computed columns readable aliases. Return raw numbers: do not format, round or convert money.
- For "top N" questions, ORDER BY the measure and add LIMIT N.

{schema}"""


class SQLDraft(BaseModel):
    """Structured output the LLM must return."""

    sql: str | None = Field(default=None, description="ONE SQLite SELECT statement, or null when no query should be run.")
    reason: str = Field(description="One short sentence: what the query computes, or why there is no query.")


@dataclass
class SQLAnswer:
    question: str
    status: str  # "ok" | "no_query" | "rejected" | "failed"
    sql: str | None = None
    explanation: str = ""
    columns: list[str] = field(default_factory=list)
    rows: list[list] = field(default_factory=list)
    row_count: int = 0
    truncated: bool = False
    attempts: int = 0
    error: str | None = None

    def to_dict(self) -> dict:
        return asdict(self)


class SQLAgent:
    def __init__(self, llm: BaseChatModel, db_path: Path, max_rows: int = 200,
                 timeout_seconds: float = 3.0, max_attempts: int = 2,
                 structured_output_method: str = "json_schema"):
        self.db_path = db_path
        self.max_rows = max_rows
        self.timeout_seconds = timeout_seconds
        self.max_attempts = max_attempts
        self.allowed_tables = list_tables(db_path)
        self.schema = describe_database(db_path)  # built once: the schema does not change at runtime
        self.generator = llm.with_structured_output(SQLDraft, method=structured_output_method)

    def run(self, question: str) -> SQLAnswer:
        started = time.perf_counter()
        system_prompt = SYSTEM_PROMPT.format(schema=self.schema, today=date.today().isoformat())
        messages = [SystemMessage(system_prompt), HumanMessage(question)]
        last_sql, last_error = None, None

        for attempt in range(1, self.max_attempts + 1):
            draft = _invoke_structured(self.generator, messages)
            if draft is None:
                # Smaller (e.g. local) models sometimes answer in prose instead of the required structure.
                last_error = "the model did not return the required {sql, reason} structure"
                messages.append(HumanMessage("Answer only with the required structure: the fields sql and reason."))
                continue
            logger.info("[sql_agent] attempt %d sql=%r reason=%r", attempt, draft.sql, draft.reason)

            if not draft.sql or not draft.sql.strip():
                return SQLAnswer(question, "no_query", explanation=draft.reason, attempts=attempt,
                                 error=f"No query was run: {draft.reason}")

            try:
                sql = validate_select(draft.sql, self.allowed_tables)
                result = run_read_only(self.db_path, sql, self.max_rows, self.timeout_seconds)
            except (UnsafeSQLError, SQLPermissionError) as exc:
                # A refused query is not retried: refusing is the correct outcome.
                logger.warning("[sql_agent] rejected unsafe SQL: %s", exc)
                return SQLAnswer(question, "rejected", sql=draft.sql, explanation=draft.reason,
                                 attempts=attempt, error=f"Query rejected: {exc}")
            except (InvalidSQLError, SQLExecutionError) as exc:
                # Self-correction: most failures are a wrong column or a typo,
                # and the error message tells the model exactly what to fix.
                last_sql, last_error = draft.sql, str(exc)
                logger.info("[sql_agent] attempt %d failed: %s", attempt, exc)
                messages.append(HumanMessage(
                    f"Your previous query\n{draft.sql}\nfailed with this error: {exc}\n"
                    "Write a corrected query for the same question."))
                continue

            logger.info("[sql_agent] %d row(s) in %.0f ms", len(result.rows), (time.perf_counter() - started) * 1000)
            return SQLAnswer(question, "ok", sql=sql, explanation=draft.reason, columns=result.columns,
                             rows=result.rows, row_count=len(result.rows), truncated=result.truncated,
                             attempts=attempt)

        return SQLAnswer(question, "failed", sql=last_sql, attempts=self.max_attempts,
                         error=f"No working query after {self.max_attempts} attempts. Last error: {last_error}")


def _invoke_structured(generator, messages) -> SQLDraft | None:
    """Call the structured-output model; None if it did not produce a valid SQLDraft."""
    try:
        return generator.invoke(messages)
    except ValueError as exc:  # empty or unparsable output (LangChain's and pydantic's parse errors are ValueErrors)
        logger.warning("[sql_agent] unusable structured output: %s", exc)
        return None
